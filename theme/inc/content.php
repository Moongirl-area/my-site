function sp_owner_id() {
	$admins = get_users( array( 'role' => 'administrator', 'number' => 1, 'fields' => 'ID' ) );
	return $admins ? (int) $admins[0] : 0;
}

function sp_create_pages() {
	$made = false;
	foreach ( sp_pages() as $slug => $title ) {
		if ( get_page_by_path( $slug, OBJECT, 'page' ) ) {
			continue;
		}
		wp_insert_post( array(
			'post_type'   => 'page',
			'post_status' => 'publish',
			'post_name'   => $slug,
			'post_title'  => $title,
			'post_author' => sp_owner_id(),
		) );
		$made = true;
	}
	if ( $made ) {
		flush_rewrite_rules();
	}
}

/**
 * نسخه‌ی ۴ (غذای خانگی): عنوان صفحه‌هایی که هنوز عنوان قدیمی پیش‌فرض را دارند به‌روز می‌شود.
 * اگر عنوانی را خودت در پیشخوان عوض کرده باشی، دست نمی‌خورد.
 */
function sp_retitle_pages() {
	$old = array(
		'calculator' => 'ماشین‌حساب قیمت کیک خانگی ۱۴۰۵',
		'learn'      => 'آموزش قیمت‌گذاری کیک خانگی',
	);
	$new = sp_pages();
	foreach ( $old as $slug => $old_title ) {
		$page = get_page_by_path( $slug, OBJECT, 'page' );
		if ( $page && $page->post_title === $old_title ) {
			wp_update_post( array( 'ID' => $page->ID, 'post_title' => $new[ $slug ] ) );
		}
	}
}

